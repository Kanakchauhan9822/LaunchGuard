const { aiConfig } = require("../config/ai")
const { scanWithGitleaks } = require("./gitleaks.service")
const { createHash } = require("node:crypto")

async function prepareImprovementBatches(files, signal) {
  signal?.throwIfAborted()
  const candidates = files.filter(file => /\.(js|jsx|mjs|cjs|ts|tsx)$/.test(file.path))
    .sort((first, second) => first.path.localeCompare(second.path))
  const excluded = []
  const batches = []
  let batch = []
  let characters = 0

  const secretPaths = await getSecretPaths(candidates.filter(file => !isGeneratedFile(file)), signal)

  for (const file of candidates) {
    signal?.throwIfAborted()

    const generated = isGeneratedFile(file)

    if (generated || secretPaths.has(file.path) || !file.content.trim()) {
      excluded.push({ path: file.path, reason: generated ? "generated-code" : secretPaths.has(file.path) ? "secret-detected" : "empty-file" })
      continue
    }

    const content = file.content.replace(/\r\n/g, "\n")
    let start = 0
    let startLine = 1

    while (start < content.length) {
      let end = Math.min(start + aiConfig.maxImprovementCharacters, content.length)
      const newline = content.lastIndexOf("\n", end - 1)

      if (end < content.length && newline >= start) {
        end = newline + 1
      }

      const raw = content.slice(start, end)
      const part = {
        path: file.path,
        startLine,
        startOffset: start,
        content: raw.endsWith("\n") ? raw.slice(0, -1) : raw
      }
      part.key = createHash("sha256").update(JSON.stringify(part)).digest("hex")

      if (
        batch.length >= aiConfig.maxImprovementFiles ||
        characters + part.content.length > aiConfig.maxImprovementCharacters ||
        batch.some(previous => previous.path === part.path)
      ) {
        batches.push(batch)
        batch = []
        characters = 0
      }

      batch.push(part)
      characters += part.content.length
      startLine += raw.split("\n").length - 1
      start = end
    }
  }

  if (batch.length > 0) {
    batches.push(batch)
  }

  return { batches, excluded, eligibleFiles: candidates.length }
}

function isGeneratedFile(file) {
  return (
    /(^|\/)(dist|build|out|generated|__generated__)\//i.test(file.path) ||
    /(?:\.min|\.bundle|\.generated|\.g)\.(?:js|jsx|mjs|cjs|ts|tsx)$/i.test(file.path) ||
    /(?:^|\n)\s*(?:\/\/|\/\*|\*)[^\n]*(?:@generated\b|code generated\b.*do not edit|(?:auto[- ]generated|automatically generated|generated by)\b)/i.test(file.content.slice(0, 2000))
  )
}

async function getSecretPaths(files, signal) {
  if (files.length === 0) {
    return new Set()
  }

  const scan = await scanWithGitleaks(files, signal)

  if (scan.outcome.status !== "completed") {
    throw new Error("Could not check source files for secrets")
  }

  return new Set(scan.findings.map(finding => finding.filePath))
}

module.exports = {
  prepareImprovementBatches
}
